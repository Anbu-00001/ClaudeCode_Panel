#!/usr/bin/env bash
#
# ccpanel — let Claude see its own mistakes straight away
#
# Runs right after Claude edits a file, checks that one file with whatever
# checker this project already uses, and hands any errors straight back to
# Claude before it reports being finished.
#
# Why this exists: without it, the only thing that notices a mistake is you,
# minutes later. Claude writes code, says "done", and you find the broken part.
# This closes that loop in seconds instead, at no cost.
#
# Rules: nothing is installed, nothing is guessed. Only checkers already present
# in the project are used. Any error, timeout, or unknown situation stays silent.

set +u

# `timeout` is coreutils and normally present, but a hook must never fail
# because a helper is missing. Falls back to running the command unbounded.
bounded() {
  local secs="$1"; shift
  if command -v timeout >/dev/null 2>&1; then timeout "$secs" "$@"; else "$@"; fi
}
trap 'exit 0' ERR

BUDGET=8            # seconds; a slow check is worse than no check
MAX_CHARS=3000      # keep the report small

INPUT=$(head -c 1000000 2>/dev/null | tr -d '\000' 2>/dev/null)
[ -z "$INPUT" ] && exit 0

read_field() {
  if command -v jq >/dev/null 2>&1; then
    printf '%s' "$INPUT" | jq -r "$1 // empty" 2>/dev/null && return 0
  fi
  if command -v node >/dev/null 2>&1; then
    printf '%s' "$INPUT" | node -e '
      let r="";process.stdin.on("data",d=>r+=d);process.stdin.on("end",()=>{
      try{const o=JSON.parse(r);const v='"$2"';if(v!=null)process.stdout.write(String(v));}catch(e){}});' 2>/dev/null && return 0
  fi
  if command -v python3 >/dev/null 2>&1; then
    printf '%s' "$INPUT" | python3 -c '
import sys,json
try:
    o=json.load(sys.stdin); v='"$3"'
    if v is not None: sys.stdout.write(str(v))
except Exception: pass' 2>/dev/null && return 0
  fi
  return 1
}

TOOL=$(read_field '.tool_name' 'o.tool_name' 'o.get("tool_name")')
case "$TOOL" in Edit|Write|NotebookEdit) ;; *) exit 0 ;; esac

FILE=$(read_field '.tool_input.file_path' 'o.tool_input&&o.tool_input.file_path' 'o.get("tool_input",{}).get("file_path")')
CWD=$(read_field '.cwd' 'o.cwd' 'o.get("cwd")')
[ -z "$FILE" ] && exit 0
[ -f "$FILE" ] || exit 0
[ -z "$CWD" ] && CWD="$PWD"

NOTES=""
add_note() { NOTES="${NOTES}$1
"; }

# --- Is this file even meant to be edited by hand? ----------------------------
case "$FILE" in
  */node_modules/*|*/vendor/*|*/.venv/*|*/dist/*|*/build/*|*/target/*)
    add_note "This file is not part of the source: it lives in a folder that gets regenerated or installed. Editing it here will be wiped out. Change the source it comes from instead." ;;
esac

BASE=$(basename "$FILE")
case "$BASE" in
  package-lock.json|pnpm-lock.yaml|yarn.lock|Cargo.lock|poetry.lock|go.sum|composer.lock)
    add_note "This file is written by the package manager, not by hand. Run the install command instead of editing it." ;;
  *.min.js|*.min.css|*.map)
    add_note "This file is generated output. Edit the original source instead." ;;
esac

# A generated-file marker near the top of the file is the project telling us directly.
if head -c 2000 "$FILE" 2>/dev/null | grep -qiE '(do not edit|@generated|autogenerated|auto-generated|code generated by)'; then
  add_note "This file says near the top that it is generated and should not be edited by hand. Find what generates it and change that instead."
fi

# --- Check the file with whatever this project already uses -------------------
# Nothing is installed and nothing is assumed: each checker runs only when both
# the config and the tool are actually present.
run_check() {
  bounded "$BUDGET" "$@" 2>&1
}

CHECK_OUTPUT=""
CHECK_NAME=""

case "$FILE" in
  *.ts|*.tsx)
    if [ -f "$CWD/tsconfig.json" ] && [ -x "$CWD/node_modules/.bin/tsc" ]; then
      CHECK_NAME="the project's type checker"
      CHECK_OUTPUT=$(cd "$CWD" && run_check ./node_modules/.bin/tsc --noEmit -p tsconfig.json | grep -F "$(basename "$FILE")" | head -12)
    fi
    ;;
  *.py)
    if [ -x "$CWD/.venv/bin/ruff" ]; then
      CHECK_NAME="ruff"
      CHECK_OUTPUT=$(cd "$CWD" && run_check ./.venv/bin/ruff check "$FILE" | head -12)
    elif command -v ruff >/dev/null 2>&1 && { [ -f "$CWD/pyproject.toml" ] || [ -f "$CWD/ruff.toml" ]; }; then
      CHECK_NAME="ruff"
      CHECK_OUTPUT=$(cd "$CWD" && run_check ruff check "$FILE" | head -12)
    fi
    ;;
  *.rs)
    if [ -f "$CWD/Cargo.toml" ] && command -v cargo >/dev/null 2>&1; then
      CHECK_NAME="cargo"
      CHECK_OUTPUT=$(cd "$CWD" && run_check cargo check --quiet | head -12)
    fi
    ;;
  *.go)
    if [ -f "$CWD/go.mod" ] && command -v go >/dev/null 2>&1; then
      CHECK_NAME="go vet"
      CHECK_OUTPUT=$(cd "$CWD" && run_check go vet ./... | head -12)
    fi
    ;;
  *.json)
    if command -v python3 >/dev/null 2>&1; then
      CHECK_NAME="a check that the file is still valid"
      CHECK_OUTPUT=$(run_check python3 -c "import json,sys; json.load(open(sys.argv[1]))" "$FILE" | tail -3)
    fi
    ;;
esac

if [ -n "$CHECK_OUTPUT" ]; then
  add_note "Problems found by ${CHECK_NAME} in the file just edited:
${CHECK_OUTPUT}
Fix these before telling the user the work is done."
fi

[ -z "$NOTES" ] && exit 0

NOTES=$(printf '%s' "$NOTES" | head -c "$MAX_CHARS")

if command -v jq >/dev/null 2>&1; then
  jq -nc --arg c "$NOTES" \
    '{hookSpecificOutput:{hookEventName:"PostToolUse", additionalContext:$c}}' 2>/dev/null && exit 0
fi

ESC=$(printf '%s' "$NOTES" | sed -e 's/\\/\\\\/g' -e 's/"/\\"/g' | awk 'BEGIN{ORS=""}{print (NR>1?"\\n":"") $0}')
printf '{"hookSpecificOutput":{"hookEventName":"PostToolUse","additionalContext":"%s"}}\n' "$ESC"
exit 0
